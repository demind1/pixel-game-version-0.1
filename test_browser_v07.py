from playwright.sync_api import sync_playwright
import json, pathlib, time
out=pathlib.Path('/mnt/data/XENOMORPH_HIVEBREAK_v07')
errors=[]
with sync_playwright() as pw:
 browser=pw.chromium.launch(headless=True,executable_path='/usr/bin/chromium',args=['--no-sandbox'])
 page=browser.new_page(viewport={'width':1200,'height':750}, device_scale_factor=1)
 page.on('pageerror',lambda e:errors.append('pageerror: '+str(e)))
 page.on('console',lambda m: errors.append('console: '+m.text) if m.type=='error' else None)
 page.goto('file:///mnt/data/XENOMORPH_HIVEBREAK_v07/index.html',wait_until='domcontentloaded')
 page.wait_for_function('window.HIVEBREAK && window.HIVEBREAK.ready',timeout=30000)
 print('ready',page.evaluate('HIVEBREAK.ready'), 'errors',errors)
 page.wait_for_timeout(450)
 page.screenshot(path=str(out/'v07_menu.png'))
 page.evaluate('HIVEBREAK.start(0)')
 page.wait_for_timeout(600)
 page.screenshot(path=str(out/'v07_play.png'))
 print('screen',page.evaluate('HIVEBREAK.screen'),'enemy list',page.evaluate('HIVEBREAK.enemyTypes'))
 page.keyboard.down('d');page.wait_for_timeout(1600);page.keyboard.up('d')
 for key in ['j','j','k','l','u']:
  page.keyboard.press(key);page.wait_for_timeout(180)
 print('world state',page.evaluate('({level:HIVEBREAK.state.level, enemies:HIVEBREAK.enemies.length, hp:HIVEBREAK.players[0].hp, energy:HIVEBREAK.players[0].energy})'))
 page.screenshot(path=str(out/'v07_combat.png'))
 page.keyboard.press('Escape');page.wait_for_timeout(200);print('pause',page.evaluate('HIVEBREAK.screen'))
 page.keyboard.press('Escape');page.wait_for_timeout(200)
 page.evaluate('HIVEBREAK.setLevel(2)')
 page.wait_for_timeout(400)
 page.screenshot(path=str(out/'v07_reactor.png'))
 page.evaluate('HIVEBREAK.spawnBoss()')
 page.wait_for_timeout(350)
 page.screenshot(path=str(out/'v07_boss.png'))
 page.evaluate('HIVEBREAK.damageBoss(20000)')
 page.wait_for_timeout(2350)
 print('bossclear',page.evaluate('HIVEBREAK.screen'))
 page.keyboard.press('Escape');page.wait_for_timeout(160)
 print('screen',page.evaluate('HIVEBREAK.screen'))
 browser.close()
print('ERRORS',errors)
